"""Regenerate the fixed-seed Lean certificate using the Python standard library."""

import argparse
from fractions import Fraction as Q
import json
from math import lcm
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
RADIUS = Q(1359451, 79000000)
EXTRA = (528344, Q(4737613, 31600000))
MAX_SPEED = 820800
WITNESS_PAIRS = [
    (Q(4912699, 25280000), Q(8072699, 25280000)),
    (Q(5032031, 19750000), Q(2558051, 7900000)),
    (Q(12288, 71731), Q(2159, 6761)),
    (Q(147331293, 410800000), Q(38586773, 79000000)),
    (Q(4406, 13607), Q(10660, 29723)),
    (Q(12288, 71731), Q(5953, 7887)),
]


def uncovered(arcs, *, include_isolated):
    """Return gap closures in [0, 1], keeping touching points for open arcs."""
    gaps = []
    right = Q(0)
    for lo, hi, _, _ in sorted(arcs):
        if right < lo or (include_isolated and right == lo):
            gaps.append((right, lo))
        right = max(right, hi)
    if right < 1 or (include_isolated and right == 1):
        gaps.append((right, Q(1)))
    return gaps


def covering_chain(arcs):
    """Choose the arc reaching furthest to the right from each endpoint."""
    arcs = sorted(arcs)
    index = 0
    right = Q(0)
    chain = []
    while right < 1:
        end = right
        while index < len(arcs) and arcs[index][0] <= right:
            _, hi, track, winding = arcs[index]
            if hi > end:
                end = hi
                selected = (track, winding)
            index += 1
        if end == right:
            raise ValueError(f"Covering chain stops at {right}")
        chain.append(selected)
        right = end
    return chain


def definition(name, type_, value):
    return f"def {name} : {type_} := {value}\n"


def pair_list(name, pairs):
    items = ",\n  ".join(f"({a}, {b})" for a, b in pairs)
    return definition(name, "List (Nat × Nat)", f"[\n  {items}\n]")


def scale(value, denominator):
    scaled = value * denominator
    if scaled.denominator != 1:
        raise ValueError(f"Inexact scaling of {value} by {denominator}")
    return int(scaled)


def generate(data):
    speed, phase = EXTRA
    track_phases = [
        (v, Q(a, data["shift_den"]))
        for v, a in zip(data["speeds"], data["shift_num"], strict=True)
    ]
    seed_arcs = []
    for track, (v, s) in enumerate(track_phases):
        for k in range(v + 2):
            lo, hi = (k - s - RADIUS) / v, (k - s + RADIUS) / v
            if lo <= 1 and hi >= 0:
                seed_arcs.append((lo, hi, track, k))

    longest = max(uncovered(seed_arcs, include_isolated=True), key=lambda gap: gap[1] - gap[0])
    if 2 * RADIUS >= (MAX_SPEED + 1) * (longest[1] - longest[0]):
        raise ValueError("The longest gap does not justify the speed cutoff")
    phase_den = lcm(data["shift_den"], RADIUS.denominator, phase.denominator)
    witness_den = lcm(
        phase_den, *(time.denominator for pair in [longest, *WITNESS_PAIRS] for time in pair)
    )
    arcs = seed_arcs.copy()
    for lo, hi in uncovered(seed_arcs, include_isolated=False):
        winding = round(speed * (lo + hi) / 2 + phase)
        arcs.append((
            (winding - phase - RADIUS) / speed,
            (winding - phase + RADIUS) / speed,
            len(track_phases),
            winding,
        ))
    chain = covering_chain(arcs)
    seed = pair_list("seed", [(v, scale(s, phase_den)) for v, s in track_phases])
    source = "\n".join([
        "-- Generated by scripts/rebuild_frozen_data.py from the published 57-runner seed.",
        "module", "", "@[expose] public section", "", "namespace MathLab.Frozen",
        definition("S", "Nat", phase_den),
        definition("T", "Nat", witness_den),
        definition("smallR", "Nat", scale(RADIUS, phase_den)),
        definition("r", "Nat", scale(RADIUS, witness_den)),
        definition("maxSpeed", "Nat", MAX_SPEED),
        definition("gapLo", "Nat", scale(longest[0], witness_den)),
        definition("gapHi", "Nat", scale(longest[1], witness_den)),
        seed,
        definition("extra", "Nat × Nat", f"({speed}, {scale(phase, phase_den)})"),
        pair_list("pairs", [(scale(a, witness_den), scale(b, witness_den)) for a, b in WITNESS_PAIRS]),
        pair_list("chain", chain),
        "end MathLab.Frozen", "",
    ])
    return source, seed, len(chain)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="rewrite MathLab/FrozenData.lean")
    options = parser.parse_args()
    data = json.loads((ROOT / "data/seed-57.json").read_text())
    source, seed, chain_length = generate(data)
    path = ROOT / "MathLab/FrozenData.lean"
    if options.write:
        path.write_text(source)
    elif path.read_text() != source:
        raise SystemExit("MathLab/FrozenData.lean differs from the regenerated certificate")
    challenge = (ROOT / "Challenge.lean").read_text()
    if seed not in challenge or definition("S", "Nat", lcm(
        data["shift_den"], RADIUS.denominator, EXTRA[1].denominator
    )) not in challenge:
        raise SystemExit("Challenge.lean differs from the regenerated seed")
    print(f"Matched {len(data['speeds'])} seed tracks, {len(WITNESS_PAIRS)} witness pairs, "
          f"and a {chain_length}-arc covering chain")


if __name__ == "__main__":
    main()
