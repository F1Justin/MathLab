"""Generate concrete integer evidence, without using a Lean proof or trusted oracle."""
from fractions import Fraction as Q
from math import lcm
from pathlib import Path
import json
from optimal_extension import ROOT, strict_residual, gaps

SEED=ROOT/'package1/results/known_slr_57.json'
OUT=ROOT/'lean/MathLab/FrozenData.lean'


def generate():
    data=json.loads(SEED.read_text())
    d=Q(1359451,79000000)
    speed=528344
    phase=Q(4737613,31600000)
    pairs=[(Q(4912699,25280000),Q(8072699,25280000)),
           (Q(5032031,19750000),Q(2558051,7900000)),
           (Q(12288,71731),Q(2159,6761)),
           (Q(147331293,410800000),Q(38586773,79000000)),
           (Q(4406,13607),Q(10660,29723)),
           (Q(12288,71731),Q(5953,7887))]
    longest=max(strict_residual(data,d),key=lambda ab:ab[1]-ab[0])
    B=820800
    assert 2*d < (B+1)*(longest[1]-longest[0])
    S=lcm(data['shift_den'],d.denominator,phase.denominator)
    T=lcm(S,*(p.denominator for pair in [longest,*pairs] for p in pair))
    seeds=[(v,Q(a,data['shift_den'])) for v,a in zip(data['speeds'],data['shift_num'])]
    line=lambda name,typ,expr:f'def {name} : {typ} := {expr}\n'
    def listing(name,rows,typ='List (Nat × Nat)'):
        return line(name,typ,'[\n  '+',\n  '.join(f'({a}, {b})' for a,b in rows)+'\n]')
    def scale(t,den):
        assert (t*den).denominator==1
        return int(t*den)
    # A covering chain uses every base arc as an option but only eleven of the fast arcs.
    arcs=[]
    for i,(v,s) in enumerate(seeds):
        for k in range(v+2):
            a,b=(k-s-d)/v,(k-s+d)/v
            if b>=0 and a<=1:arcs.append((a,b,i,k))
    for a,b in gaps(data,d):
        k=round(speed*(a+b)/2+phase)
        arcs.append(((k-phase-d)/speed,(k-phase+d)/speed,len(seeds),k))
    arcs.sort()
    j=0;right=Q(0);chain=[]
    while right<1:
        end=right
        while j<len(arcs) and arcs[j][0]<=right:
            _,b,i,k=arcs[j]
            if b>end:end,choice=b,(i,k)
            j+=1
        assert end>right
        chain.append(choice);right=end
    return '\n'.join(['-- Generated by research/runner/lean_frozen_data.py from the published 57-runner seed.',
        'namespace MathLab.Frozen',line('S','Nat',S),line('T','Nat',T),
        line('smallR','Nat',scale(d,S)),line('r','Nat',scale(d,T)),line('maxSpeed','Nat',B),
        line('gapLo','Nat',scale(longest[0],T)),line('gapHi','Nat',scale(longest[1],T)),
        listing('seed',[(v,scale(s,S)) for v,s in seeds]),
        line('extra','Nat × Nat',f'({speed}, {scale(phase,S)})'),
        listing('pairs',[(scale(a,T),scale(b,T)) for a,b in pairs]),
        listing('chain',chain),'end MathLab.Frozen',''])


if __name__=='__main__':
    import sys
    result=generate()
    if '--check' in sys.argv:
        assert OUT.read_text()==result
    else:OUT.write_text(result)
